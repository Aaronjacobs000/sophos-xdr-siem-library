// The parts of tools/port-gitleaks.mjs that need no network: read gitleaks' default config, take
// out the generic-api-key rule and the global allowlist, write them as studio/core/gitleaks-rule.js,
// and set the gitleaks version and release checksum CI installs.

import { readToml } from './toml.mjs';

export const RULE_ID = 'generic-api-key';

// The fields the port in studio/core/gitleaks.js implements. A field outside these, such as a
// secretGroup, a path or a required rule in a later gitleaks, stops the port: the port's matching
// would have to learn it first.
const RULE_FIELDS = ['id', 'description', 'regex', 'entropy', 'keywords', 'allowlists'];
const ALLOWLIST_FIELDS = ['description', 'condition', 'regexTarget', 'regexes', 'stopwords', 'paths'];

function checkFields(obj, allowed, what) {
  const extra = Object.keys(obj).filter((k) => !allowed.includes(k));
  if (extra.length) throw new Error(`${what} has ${extra.join(', ')}, which the port doesn't implement; port it by hand first`);
}

const strings = (v, what) => {
  if (v === undefined) return undefined;
  if (!Array.isArray(v) || v.some((s) => typeof s !== 'string')) throw new Error(`${what} is not a list of strings`);
  return v;
};

function allowlist(a, what) {
  checkFields(a, ALLOWLIST_FIELDS, what);
  const out = {};
  if (a.description !== undefined) out.description = String(a.description);
  if (a.condition !== undefined) out.condition = String(a.condition);
  if (a.regexTarget !== undefined) out.regexTarget = String(a.regexTarget);
  for (const k of ['paths', 'regexes', 'stopwords']) if (a[k] !== undefined) out[k] = strings(a[k], `${what} ${k}`);
  return out;
}

// {rule, globals} from the text of gitleaks' config/gitleaks.toml. The global allowlist is
// [allowlist] in gitleaks 8.30 and may become [[allowlists]]; both are read.
export function portFromConfig(text) {
  const doc = readToml(text);
  const rules = (doc.rules || []).filter((r) => r && r.id === RULE_ID);
  if (rules.length !== 1) throw new Error(`the config has ${rules.length} ${RULE_ID} rules, not 1`);
  const r = rules[0];
  checkFields(r, RULE_FIELDS, `the ${RULE_ID} rule`);
  if (typeof r.regex !== 'string' || !r.regex) throw new Error(`the ${RULE_ID} rule has no regex`);
  const rule = {
    id: r.id,
    regex: r.regex,
    entropy: typeof r.entropy === 'number' ? r.entropy : 0,
    keywords: strings(r.keywords, 'keywords') || [],
    allowlists: (r.allowlists || []).map((a, i) => allowlist(a, `the ${RULE_ID} rule's allowlist ${i + 1}`)),
  };
  const globals = [...(doc.allowlist ? [doc.allowlist] : []), ...(doc.allowlists || [])]
    .map((a, i) => allowlist(a, `the global allowlist ${i + 1}`));
  return { rule, globals };
}

