// ci.yml with every GITLEAKS_VERSION and GITLEAKS_SHA256 line set, for each job that installs
// gitleaks. Throws if there is none, or if the two don't come in pairs.
export function setCiVersion(ci, version, sha256) {
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`${version} is not a gitleaks version`);
  if (!/^[0-9a-f]{64}$/.test(sha256)) throw new Error('the checksum is not a SHA-256');
  const versions = ci.match(/^(\s+)GITLEAKS_VERSION: \S+$/gm) || [];
  const sums = ci.match(/^(\s+)GITLEAKS_SHA256: \S+$/gm) || [];
  if (!versions.length || versions.length !== sums.length) throw new Error(`ci.yml has ${versions.length} GITLEAKS_VERSION and ${sums.length} GITLEAKS_SHA256 lines`);
  return ci.replace(/^(\s+GITLEAKS_VERSION: )\S+$/gm, `$1${version}`).replace(/^(\s+GITLEAKS_SHA256: )\S+$/gm, `$1${sha256}`);
}

// The linux_x64 tarball's SHA-256 from the release's checksums file.
export function tarballSha256(checksums, version) {
  const name = `gitleaks_${version}_linux_x64.tar.gz`;
  const line = checksums.split('\n').map((l) => l.trim().split(/\s+/)).find((p) => p[1] === name);
  if (!line || !/^[0-9a-f]{64}$/.test(line[0])) throw new Error(`no checksum for ${name}`);
  return line[0];
}

// ATTRIBUTIONS.md with the gitleaks version its rows credit set to version.
export function setAttributionVersion(text, version) {
  const re = /(\[gitleaks\]\(https:\/\/github\.com\/gitleaks\/gitleaks\) v)\d+\.\d+\.\d+/g;
  if (!re.test(text)) throw new Error('ATTRIBUTIONS.md credits no gitleaks version');
  return text.replace(re, `$1${version}`);
}
